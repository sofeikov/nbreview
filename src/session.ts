// Everything known about the pull request under review: its notebooks as review documents, the
// other changed files, and where each existing GitHub thread belongs. No VS Code APIs in here.
import type { GhThread, GitHub, LastReview, PrFile, PrInfo } from './github.ts';
import { emptyNotebook, parseNotebook } from './core/notebook.ts';
import { buildReviewDoc, docLineForSource, type ReviewDoc } from './core/reviewDoc.ts';
import { parsePatch, type CommentableLines } from './core/patch.ts';
import { locateNotebookThread, matchExportedLine, nbdevSourceForLine, type Side } from './core/anchor.ts';
import { locateFileThread } from './core/fileComments.ts';

export interface NotebookEntry {
  file: PrFile;
  path: string;
  base: ReviewDoc;
  head: ReviewDoc;
  commentable: CommentableLines;
  error?: string;
}

export interface OtherFile {
  file: PrFile;
  /** Module generated by nbdev from a notebook: its threads are also shown on the notebook cell. */
  generated: boolean;
  /** Threads on this file also shown on a notebook cell. */
  movedThreads: number;
  /** Threads on this file. */
  threads: number;
  /** For generated modules: the notebook nbdev exported it from. */
  sourceNotebook?: string;
}

export interface PlacedThread {
  gh: GhThread;
  nbPath: string;
  side: Side;
  docLine: number;
  /** First line, for comments on several lines. */
  startDocLine?: number;
  note?: string;
  /** Where the thread really lives on GitHub when it was moved from a generated .py file. */
  movedFrom?: string;
}

/** A GitHub thread on an ordinary (non-notebook) file, at its line in that file. */
export interface FileThread {
  gh: GhThread;
  path: string;
  side: Side;
  docLine: number;
  startDocLine?: number;
  note?: string;
}

const GENERATED_HEADER = '# AUTOGENERATED! DO NOT EDIT!';

export class ReviewSession {
  readonly notebooks = new Map<string, NotebookEntry>();
  readonly others: OtherFile[] = [];
  placed: PlacedThread[] = [];
  /** Threads on ordinary files, by path. */
  fileThreads = new Map<string, FileThread[]>();
  /** The viewer's pending review on GitHub, if they have started one. */
  pendingReviewId: string | undefined;
  /** Comments in the pending review, on any file (some may not be on notebooks). */
  pendingCount = 0;
  /** GitHub "Viewed" state per file path. */
  viewed = new Map<string, boolean>();
  /** Files GitHub unchecked because they changed after the viewer marked them viewed. */
  viewedDismissed = new Set<string>();
  /** The viewer's last submitted review, if they have reviewed this pull request before. */
  lastReview?: LastReview;
  /**
   * Paths changed since that review. Undefined when there is no review, or when GitHub can't
   * compare the two commits (see sinceReviewProblem).
   */
  changedSinceReview?: Set<string>;
  sinceReviewProblem?: string;
  private readonly sinceDocs = new Map<string, Promise<ReviewDoc>>();
  private readonly contents = new Map<string, Promise<string | undefined>>();
  private readonly commentables = new Map<string, CommentableLines>();

  private constructor(
    readonly gh: GitHub,
    readonly pr: PrInfo,
    readonly files: PrFile[],
  ) {}

  static async load(gh: GitHub, owner: string, repo: string, number: number, progress?: (msg: string) => void): Promise<ReviewSession> {
    progress?.('Fetching pull request…');
    // Everything that only needs the pull request number is requested at once.
    const [pr, files, found, viewed, lastReview] = await Promise.all([
      gh.getPr(owner, repo, number),
      gh.listFiles(owner, repo, number),
      gh.getThreads(owner, repo, number),
      gh.getViewed(owner, repo, number).catch(() => ({ viewed: new Map<string, boolean>(), dismissed: new Set<string>() })),
      gh.lastReview(owner, repo, number).catch(() => undefined),
    ]);
    const session = new ReviewSession(gh, pr, files);
    session.viewed = viewed.viewed;
    session.viewedDismissed = viewed.dismissed;
    session.lastReview = lastReview;
    progress?.(`Loading ${files.filter(isNotebook).length} notebooks…`);
    await Promise.all([session.loadFiles(), session.loadChangesSinceReview()]);
    await session.placeThreads(found.threads, found.pendingReviewId);
    return session;
  }

  /** Works out which files changed after the viewer's last review. */
  private async loadChangesSinceReview(): Promise<void> {
    const last = this.lastReview;
    if (!last) {
      return;
    }
    if (last.sha === this.pr.headSha) {
      this.changedSinceReview = new Set();
      return;
    }
    const changed = await this.gh.changedBetween(this.pr.owner, this.pr.repo, last.sha, this.pr.headSha).catch(() => undefined);
    if (changed) {
      this.changedSinceReview = new Set(changed);
    } else {
      this.sinceReviewProblem = `GitHub can't compare the commit of your last review (${last.sha.slice(0, 7)}) with the pull request, perhaps after a force push.`;
    }
  }

  /** Whether a file changed after the viewer's last review. */
  changedSince(path: string): boolean {
    return this.changedSinceReview?.has(path) ?? false;
  }

  /** A notebook as it was at the viewer's last review (empty if it didn't exist then). */
  sinceReviewDoc(nbPath: string): Promise<ReviewDoc> | undefined {
    const last = this.lastReview;
    const entry = this.notebooks.get(nbPath);
    if (!last || !entry) {
      return undefined;
    }
    let doc = this.sinceDocs.get(nbPath);
    if (!doc) {
      doc = this.contentAt(nbPath, last.sha)
        .then(text => (text === undefined && entry.file.previousFilename ? this.contentAt(entry.file.previousFilename, last.sha) : text))
        .then(text => buildReviewDoc(text === undefined ? emptyNotebook() : parseNotebook(text)));
      this.sinceDocs.set(nbPath, doc);
    }
    return doc;
  }

  /** Cached raw content of a changed file on one side of the PR. */
  content(path: string, side: Side): Promise<string | undefined> {
    const file = this.files.find(f => f.filename === path);
    const ref = side === 'LEFT' ? this.pr.baseSha : this.pr.headSha;
    const at = side === 'LEFT' ? file?.previousFilename ?? path : path;
    if ((side === 'LEFT' && file?.status === 'added') || (side === 'RIGHT' && file?.status === 'removed')) {
      return Promise.resolve(undefined);
    }
    return this.contentAt(at, ref);
  }

  /** Cached raw content of a file at a commit. */
  contentAt(path: string, ref: string): Promise<string | undefined> {
    const key = `${ref}:${path}`;
    let p = this.contents.get(key);
    if (!p) {
      p = this.gh.getContent(this.pr.owner, this.pr.repo, path, ref);
      this.contents.set(key, p);
    }
    return p;
  }

  private async loadFiles(): Promise<void> {
    await pool(this.files, 16, async file => {
      if (isNotebook(file)) {
        const [baseText, headText] = await Promise.all([this.content(file.filename, 'LEFT'), this.content(file.filename, 'RIGHT')]);
        let error: string | undefined;
        const parse = (text: string | undefined) => {
          if (text === undefined) {
            return emptyNotebook();
          }
          try {
            return parseNotebook(text);
          } catch (e) {
            error = String(e);
            return emptyNotebook();
          }
        };
        this.notebooks.set(file.filename, {
          file,
          path: file.filename,
          base: buildReviewDoc(parse(baseText)),
          head: buildReviewDoc(parse(headText)),
          commentable: parsePatch(file.patch),
          error,
        });
      } else {
        let generated = file.filename.endsWith('/_modidx.py');
        let sourceNotebook: string | undefined;
        if (!generated && file.filename.endsWith('.py')) {
          const text = await this.content(file.filename, file.status === 'removed' ? 'LEFT' : 'RIGHT');
          generated = !!text?.startsWith(GENERATED_HEADER);
          const m = generated ? /File to edit: (\S+\.ipynb)/.exec(text!.slice(0, 300)) : null;
          sourceNotebook = m ? joinPath(dirname(file.filename), m[1]) : undefined;
        }
        this.others.push({ file, generated, movedThreads: 0, threads: 0, sourceNotebook });
      }
    });
    this.others.sort((a, b) => a.file.filename.localeCompare(b.file.filename));
  }

  async loadThreads(): Promise<void> {
    const found = await this.gh.getThreads(this.pr.owner, this.pr.repo, this.pr.number);
    await this.placeThreads(found.threads, found.pendingReviewId);
  }

  /** Puts each thread on its notebook cell, moving threads on generated modules to their notebook. */
  async placeThreads(found: GhThread[], pendingReviewId?: string): Promise<void> {
    this.pendingReviewId = pendingReviewId;
    // Right after a pending review is discarded, GitHub can still return its comments for a
    // moment; without a pending review they are stale.
    const threads = pendingReviewId
      ? found
      : found.map(t => ({ ...t, comments: t.comments.filter(c => !c.pending) })).filter(t => t.comments.length > 0);
    this.pendingCount = threads.reduce((n, t) => n + t.comments.filter(c => c.pending).length, 0);
    const placed: PlacedThread[] = [];
    const fileThreads = new Map<string, FileThread[]>();
    for (const o of this.others) {
      o.movedThreads = 0;
      o.threads = 0;
    }
    for (const t of threads) {
      const nb = this.notebooks.get(t.path);
      if (nb) {
        const where = locateNotebookThread({ ...t, body: t.comments[0].body }, nb);
        if (where) {
          placed.push({ gh: t, nbPath: nb.path, ...where });
        }
        continue;
      }
      const other = this.others.find(o => o.file.filename === t.path);
      if (!other) {
        continue;
      }
      other.threads++;
      fileThreads.set(t.path, [...(fileThreads.get(t.path) ?? []), { gh: t, path: t.path, ...locateFileThread(t) }]);
      // A comment on a module nbdev generated is also shown on the notebook cell it came from.
      const moved = other.generated ? await this.placeFromGenerated(t) : undefined;
      if (moved) {
        placed.push(moved);
        other.movedThreads++;
      }
    }
    this.placed = placed;
    this.fileThreads = fileThreads;
  }

  private async placeFromGenerated(t: GhThread): Promise<PlacedThread | undefined> {
    const line = t.line ?? t.originalLine;
    if (line === null) {
      return undefined;
    }
    const side: Side = t.diffSide;
    const text = await this.content(t.path, side);
    if (!text) {
      return undefined;
    }
    const src = nbdevSourceForLine(t.path, text, line);
    const nb = src && this.notebooks.get(src.notebookPath);
    if (!src || !nb) {
      return undefined;
    }
    const doc = side === 'LEFT' ? nb.base : nb.head;
    const cell = src.cellId.startsWith('index-')
      ? doc.notebook.cells[Number(src.cellId.slice(6))]
      : doc.notebook.cells.find(c => c.id === src.cellId);
    if (!cell) {
      return undefined;
    }
    const docLine = docLineForSource(doc, cell.id, matchExportedLine(cell, src));
    if (docLine === undefined) {
      return undefined;
    }
    return {
      gh: t,
      nbPath: nb.path,
      side,
      docLine,
      movedFrom: `${t.path}:${line}`,
      note: t.isOutdated ? 'outdated' : undefined,
    };
  }

  /** Lines of a changed file that GitHub accepts line comments on. */
  commentable(path: string): CommentableLines {
    let c = this.commentables.get(path);
    if (!c) {
      c = parsePatch(this.files.find(f => f.filename === path)?.patch);
      this.commentables.set(path, c);
    }
    return c;
  }

  /** Every review thread, on notebooks and ordinary files, each once. */
  allThreads(): GhThread[] {
    const seen = new Map<string, GhThread>();
    for (const p of this.placed) {
      seen.set(p.gh.id, p.gh);
    }
    for (const list of this.fileThreads.values()) {
      for (const f of list) {
        seen.set(f.gh.id, f.gh);
      }
    }
    return [...seen.values()];
  }

  threadsFor(nbPath: string): PlacedThread[] {
    return this.placed.filter(p => p.nbPath === nbPath);
  }

  /** Generated modules exported from a notebook, so they can be marked viewed together with it. */
  generatedFrom(nbPath: string): string[] {
    return this.others.filter(o => o.sourceNotebook === nbPath).map(o => o.file.filename);
  }
}

export function isNotebook(file: PrFile): boolean {
  return file.filename.endsWith('.ipynb');
}

function dirname(path: string): string {
  const i = path.lastIndexOf('/');
  return i < 0 ? '' : path.slice(0, i);
}

function joinPath(base: string, rel: string): string {
  const parts = base ? base.split('/') : [];
  for (const piece of rel.split('/')) {
    if (piece === '..') {
      parts.pop();
    } else if (piece !== '.' && piece !== '') {
      parts.push(piece);
    }
  }
  return parts.join('/');
}

async function pool<T>(items: T[], size: number, fn: (item: T) => Promise<void>): Promise<void> {
  let next = 0;
  const workers = Array.from({ length: Math.min(size, items.length) }, async () => {
    while (next < items.length) {
      await fn(items[next++]);
    }
  });
  await Promise.all(workers);
}
